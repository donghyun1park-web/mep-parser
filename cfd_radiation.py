class RadiationInputError(ValueError):
    """Raised when an enclosure is not evidenced well enough for radiation."""


def _sha256(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _positive_number(value, label):
    if not isinstance(value, Real) or isinstance(value, bool) or not math.isfinite(value):
        raise RadiationInputError(f"{label} 값은 유한한 숫자여야 합니다.")
    if value <= 0:
        raise RadiationInputError(f"{label} 값은 0보다 커야 합니다.")
    return float(value)


def _emissivity(value, label):
    value = _positive_number(value, label)
    if value > 1:
        raise RadiationInputError(f"{label} 값은 1 이하여야 합니다.")
    return value


def validate_radiation_input(*, engine, surfaces):
    """Validate the minimum evidence for a closed body-fitted enclosure.

    The returned records are copies, so callers can safely serialize the
    validation evidence without mutating an import manifest.  This validates
    *input readiness*, not an OpenFOAM result or a design decision.
    """
    if not isinstance(engine, str) or not engine.startswith("body_fitted"):
        raise RadiationInputError(
            "복사 해석은 검증된 body-fitted enclosure에서만 사용할 수 있습니다."
        )
    if not isinstance(surfaces, (list, tuple)):
        raise RadiationInputError("복사 표면 목록이 필요합니다.")

    participating = []
    for raw in surfaces:
        if not isinstance(raw, dict):
            raise RadiationInputError("복사 표면은 객체여야 합니다.")
        if raw.get("participating") is not True:
            continue
        name = str(raw.get("name") or "").strip()
        patch = str(raw.get("mesh_patch_name") or "").strip()
        if not name or not patch:
            raise RadiationInputError("복사 표면에는 name과 mesh_patch_name이 필요합니다.")
        material_source = str(raw.get("material_source") or "").strip()
        if not material_source:
            raise RadiationInputError(f"복사 표면 {name}에 재질 출처가 없습니다.")
        boundary = raw.get("thermal_boundary")
        if not isinstance(boundary, dict) or not str(boundary.get("type") or "").strip():
            raise RadiationInputError(f"복사 표면 {name}에 열경계 조건이 없습니다.")
        participating.append({
            "name": name,
            "mesh_patch_name": patch,
            "role": str(raw.get("role") or "wall"),
            "emissivity": _emissivity(raw.get("emissivity"), f"복사 표면 {name} 방사율"),
            "material_source": material_source,
            "thermal_boundary": dict(boundary),
        })

    if len(participating) < 2:
        raise RadiationInputError("밀폐 복사 enclosure에는 최소 2개의 참여 표면이 필요합니다.")
    names = [item["name"] for item in participating]
    if len(set(names)) != len(names):
        raise RadiationInputError("참여 복사 표면 name이 중복되었습니다.")
    patches = [item["mesh_patch_name"] for item in participating]
    if len(set(patches)) != len(patches):
        raise RadiationInputError(
            "복사 표면은 서로 분리된 mesh patch여야 합니다. 단일 wall patch로는 복사를 활성화할 수 없습니다."
        )
    return participating


def two_plate_net_flux_w_m2(*, hot_temperature_k, cold_temperature_k,
                             hot_emissivity, cold_emissivity):
    """Return signed diffuse-grey net radiative heat flux for two infinite plates."""
    hot_temperature_k = _positive_number(hot_temperature_k, "고온 표면 온도")
    cold_temperature_k = _positive_number(cold_temperature_k, "저온 표면 온도")
    hot_emissivity = _emissivity(hot_emissivity, "고온 표면 방사율")
    cold_emissivity = _emissivity(cold_emissivity, "저온 표면 방사율")
    resistance = (1.0 / hot_emissivity) + (1.0 / cold_emissivity) - 1.0
    return STEFAN_BOLTZMANN_W_M2_K4 * (
        hot_temperature_k ** 4 - cold_temperature_k ** 4
    ) / resistance


def load_two_plate_reference(path=None):
    """Load and validate the analytical two-plate benchmark reference.

    This is a benchmark input/evidence artifact, not a result from the local
    OpenFOAM installation.  A generated solver result must be compared to it
    before a view-factor configuration can be promoted beyond the benchmark.
    """
    source = Path(path) if path is not None else _TWO_PLATE_REFERENCE_PATH
    try:
        reference = json.loads(source.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise RadiationInputError(f"두 평행판 복사 benchmark 기준값을 읽지 못했습니다: {exc}") from exc
    if reference.get("contract") != "radiation_benchmark_reference.v1":
        raise RadiationInputError("두 평행판 복사 benchmark 계약 버전이 올바르지 않습니다.")
    inputs = reference.get("input")
    expected = reference.get("expected")
    if not isinstance(inputs, dict) or not isinstance(expected, dict):
        raise RadiationInputError("두 평행판 복사 benchmark 입력 또는 기준값이 없습니다.")
    calculated = two_plate_net_flux_w_m2(
        hot_temperature_k=inputs.get("hot_temperature_k"),
        cold_temperature_k=inputs.get("cold_temperature_k"),
        hot_emissivity=inputs.get("hot_emissivity"),
        cold_emissivity=inputs.get("cold_emissivity"),
    )
    stored = _positive_number(expected.get("net_flux_w_m2"), "두 평행판 기준 열유속")
    if not math.isclose(calculated, stored, rel_tol=1e-9, abs_tol=1e-9):
        raise RadiationInputError(
            "두 평행판 복사 benchmark 기준값이 폐쇄형 해와 일치하지 않습니다."
        )
    return reference


def benchmark_reference_sha256(path=None):
    """Return the exact reference artifact identity required by a radiation run."""
    source = Path(path) if path is not None else _TWO_PLATE_REFERENCE_PATH
    try:
        return _sha256(source)
    except OSError as exc:
        raise RadiationInputError(f"두 평행판 복사 benchmark 해시를 계산하지 못했습니다: {exc}") from exc


def _nonnegative_number(value, label):
    if not isinstance(value, Real) or isinstance(value, bool) or not math.isfinite(value):
        raise RadiationInputError(f"{label} 값은 유한한 숫자여야 합니다.")
    if value < 0:
        raise RadiationInputError(f"{label} 값은 0 이상이어야 합니다.")
    return float(value)


def validate_radiation_manifest(manifest, *, thermal_input_sha256,
                                reference_path=None, case_dir=None):
    """Validate a serial two-plate benchmark from actual solver artifacts.

    Field/project radiation validation is intentionally unavailable. The
    standalone benchmark must be re-collected from its F and non-initial-time
    qr artifacts before its JSON summary can be accepted.
    """
    if not isinstance(manifest, dict):
        raise RadiationInputError("radiation manifest가 없습니다.")
    if case_dir is None:
        raise RadiationInputError(
            "A benchmark case_dir is required; a copied radiation JSON is not evidence."
        )
    if thermal_input_sha256 is not None:
        raise RadiationInputError(
            "Field/project thermal input cannot use the benchmark-only radiation contract."
        )
    if manifest.get("contract") != "radiation_manifest.v1":
        raise RadiationInputError("radiation manifest 계약 버전이 올바르지 않습니다.")
    if manifest.get("status") != "PASS":
        raise RadiationInputError("radiation manifest가 PASS 상태가 아닙니다.")
    if manifest.get("scope") != "serial_two_plate_view_factor_benchmark_only":
        raise RadiationInputError("Only the serial two-plate benchmark scope is supported.")
    if manifest.get("design_ready") is not False:
        raise RadiationInputError("A benchmark radiation manifest must never be design_ready.")
    if manifest.get("citation_status") != "BENCHMARK_ONLY":
        raise RadiationInputError("A benchmark radiation manifest must be BENCHMARK_ONLY.")
    if manifest.get("thermal_input_sha256") is not None:
        raise RadiationInputError("A benchmark radiation manifest cannot claim a field thermal input.")
    collected = collect_two_plate_view_factor_evidence(
        case_dir, reference_path=reference_path
    )
    if collected.get("status") != "PASS" or collected != manifest:
        raise RadiationInputError(
            "Radiation manifest does not match a fresh collection of F/qr benchmark evidence."
        )
    if manifest.get("benchmark_reference_sha256") != benchmark_reference_sha256(reference_path):
        raise RadiationInputError("radiation manifest의 benchmark 기준값 해시가 일치하지 않습니다.")

    reference = load_two_plate_reference(reference_path)
    acceptance = reference.get("acceptance") if isinstance(reference, dict) else {}
    factors = manifest.get("view_factors")
    if not isinstance(factors, dict) or factors.get("ok") is not True:
        raise RadiationInputError("view-factor 폐합/상호성 검증이 PASS가 아닙니다.")
    if _nonnegative_number(
            factors.get("max_row_sum_error"), "view-factor 행 폐합 오차"
    ) > float(acceptance["view_factor_row_sum_tolerance"]):
        raise RadiationInputError("view-factor 행 폐합 오차가 benchmark 허용범위를 넘었습니다.")
    if _nonnegative_number(
            factors.get("max_reciprocity_error_m2"), "view-factor 상호성 오차"
    ) > float(acceptance["view_factor_reciprocity_tolerance_m2"]):
        raise RadiationInputError("view-factor 상호성 오차가 benchmark 허용범위를 넘었습니다.")

    balance = manifest.get("energy_balance")
    if not isinstance(balance, dict):
        raise RadiationInputError("복사 에너지수지 증적이 없습니다.")
    if _nonnegative_number(
            balance.get("internal_radiation_balance_relative_error"), "내부 복사 에너지수지 오차"
    ) > float(acceptance["internal_radiation_balance_relative_error_max"]):
        raise RadiationInputError("내부 복사 에너지수지 오차가 benchmark 허용범위를 넘었습니다.")

    fields = manifest.get("fields")
    if not isinstance(fields, dict) or fields.get("qr_nonzero") is not True:
        raise RadiationInputError("복사 열유속 qr의 비영 증적이 없습니다.")
    patch_powers = manifest.get("patch_net_radiation_power_w")
    if not isinstance(patch_powers, dict) or len(patch_powers) < 2:
        raise RadiationInputError("패치별 순복사열 적분 증적이 충분하지 않습니다.")
    values = []
    for name, value in patch_powers.items():
        if not isinstance(name, str) or not name.strip():
            raise RadiationInputError("패치별 순복사열 적분의 패치명이 올바르지 않습니다.")
        values.append(_nonnegative_number(abs(value) if isinstance(value, Real) else value,
                                          "패치별 순복사열"))
    gross_power = sum(values)
    if gross_power <= 0:
        raise RadiationInputError("패치별 순복사열 적분이 모두 0입니다.")
    signed_total = sum(float(value) for value in patch_powers.values())
    calculated_balance_error = abs(signed_total) / gross_power
    if calculated_balance_error > float(acceptance["internal_radiation_balance_relative_error_max"]):
        raise RadiationInputError("패치별 순복사열 적분의 내부 수지가 허용범위를 넘었습니다.")
    output = dict(manifest)
    output["validated_for_benchmark"] = True
    output["computed_patch_radiation_balance_relative_error"] = calculated_balance_error
    return output


def view_factor_diagnostics(*, areas_m2, view_factors, tolerance=1e-6):
    """Check enclosure view-factor closure and reciprocity without a solver."""
    if not isinstance(areas_m2, (list, tuple)) or not areas_m2:
        raise RadiationInputError("view-factor 면적 목록이 필요합니다.")
    areas = [_positive_number(area, "표면 면적") for area in areas_m2]
    size = len(areas)
    if not isinstance(view_factors, (list, tuple)) or len(view_factors) != size:
        raise RadiationInputError("view-factor 행 수가 표면 수와 일치해야 합니다.")
    if not isinstance(tolerance, Real) or isinstance(tolerance, bool) or tolerance < 0:
        raise RadiationInputError("view-factor 허용오차가 올바르지 않습니다.")

    matrix = []
    for row in view_factors:
        if not isinstance(row, (list, tuple)) or len(row) != size:
            raise RadiationInputError("각 view-factor 행은 표면 수만큼의 값을 가져야 합니다.")
        clean_row = []
        for factor in row:
            if (not isinstance(factor, Real) or isinstance(factor, bool)
                    or not math.isfinite(factor) or factor < 0):
                raise RadiationInputError("view-factor는 0 이상의 유한한 숫자여야 합니다.")
            clean_row.append(float(factor))
        matrix.append(clean_row)

    row_errors = [abs(sum(row) - 1.0) for row in matrix]
    reciprocity_errors = [
        abs(areas[i] * matrix[i][j] - areas[j] * matrix[j][i])
        for i in range(size) for j in range(i + 1, size)
    ]
    max_row_sum_error = max(row_errors, default=0.0)
    max_reciprocity_error = max(reciprocity_errors, default=0.0)
    errors = []
    if max_row_sum_error > tolerance:
        errors.append("VIEW_FACTOR_ROW_CLOSURE")
    if max_reciprocity_error > tolerance:
        errors.append("VIEW_FACTOR_RECIPROCITY")
    return {
        "contract": "view_factor_diagnostics.v1",
        "ok": not errors,
        "surface_count": size,
        "tolerance": float(tolerance),
        "max_row_sum_error": max_row_sum_error,
        "max_reciprocity_error_m2": max_reciprocity_error,
        "errors": errors,
    }


