def collect_two_plate_view_factor_evidence(case_dir, *, reference_path=None):
    """Collect a serial benchmark manifest from already written OF outputs.

    This function never calls OpenFOAM and never manufactures a radiation
    result. A missing F matrix, a missing non-initial-time qr field, malformed
    field data, source drift, or a failed benchmark comparison produces a
    NOT_EVALUATED manifest instead of a PASS.
    """
    case = Path(case_dir).expanduser().resolve()
    input_path = case / "radiation_benchmark_input.json"
    try:
        benchmark_input = json.loads(input_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise RadiationInputError(
            f"생성된 두 평행판 benchmark 입력을 읽지 못했습니다: {exc}"
        ) from exc
    if benchmark_input.get("contract") != TWO_PLATE_CASE_CONTRACT:
        raise RadiationInputError("두 평행판 benchmark 입력 계약 버전이 올바르지 않습니다.")
    if benchmark_input.get("execution_mode") != "serial_only":
        raise RadiationInputError("두 평행판 benchmark는 serial_only 계약이어야 합니다.")

    reference = load_two_plate_reference(reference_path)
    reference_file = (
        Path(reference_path) if reference_path is not None else _TWO_PLATE_REFERENCE_PATH
    )
    reference_sha256 = _sha256(reference_file)
    source_ok, source_blockers, source_hashes = _source_integrity(case, benchmark_input)
    manifest = _benchmark_manifest_base(
        case, benchmark_input, reference_sha256=reference_sha256, source_hashes=source_hashes
    )
    manifest["source_integrity"] = {
        "ok": source_ok,
        "expected_hashes": dict(benchmark_input.get("source_hashes") or {}),
        "observed_hashes": source_hashes,
    }
    blockers = list(source_blockers)
    if benchmark_input.get("reference_sha256") != reference_sha256:
        blockers.append("BENCHMARK_REFERENCE_HASH_MISMATCH")

    matrix_path = case / "constant" / "F"
    if not matrix_path.is_file():
        blockers.append("VIEW_FACTOR_MATRIX_MISSING")
    else:
        manifest["solver_outputs"]["hashes"]["constant/F"] = _sha256(matrix_path)
        try:
            matrix = _parse_view_factor_matrix(matrix_path)
            matrix_meta = benchmark_input.get("view_factor_matrix")
            areas = matrix_meta.get("areas_m2") if isinstance(matrix_meta, dict) else None
            if not isinstance(areas, list) or len(matrix) != len(areas):
                raise RadiationInputError("view-factor 행렬 차원이 benchmark 표면 수와 다릅니다.")
            acceptance = reference["acceptance"]
            diagnostics = view_factor_diagnostics(
                areas_m2=areas,
                view_factors=matrix,
                tolerance=max(
                    float(acceptance["view_factor_row_sum_tolerance"]),
                    float(acceptance["view_factor_reciprocity_tolerance_m2"]),
                ),
            )
            diagnostics["available"] = True
            diagnostics["source"] = "constant/F"
            manifest["view_factors"] = diagnostics
            if not diagnostics["ok"]:
                blockers.append("VIEW_FACTOR_DIAGNOSTICS_FAILED")
        except (RadiationInputError, KeyError, TypeError, ValueError):
            blockers.append("VIEW_FACTOR_MATRIX_INVALID")

    qr_output = _latest_solver_qr(case)
    if qr_output is None:
        blockers.append("QR_FIELD_MISSING")
    else:
        _, time_name, qr_path = qr_output
        relative_qr = str(qr_path.relative_to(case)).replace("\\", "/")
        manifest["solver_outputs"]["qr_time"] = time_name
        manifest["solver_outputs"]["qr_path"] = relative_qr
        manifest["solver_outputs"]["hashes"][relative_qr] = _sha256(qr_path)
        try:
            qr_values = _parse_qr_patch_values(qr_path)
            patches = benchmark_input.get("patches")
            if not isinstance(patches, list):
                raise RadiationInputError("benchmark 표면 정의가 없습니다.")
            patch_powers = {}
            for patch in patches:
                if not isinstance(patch, dict):
                    raise RadiationInputError("benchmark 표면 정의가 올바르지 않습니다.")
                name = patch.get("name")
                if not isinstance(name, str) or name not in qr_values:
                    blockers.append(f"QR_PATCH_MISSING:{name}")
                    continue
                patch_powers[name] = qr_values[name] * _positive_number(
                    patch.get("area_m2"), f"{name} 표면적"
                )
            manifest["fields"] = {
                "qr_available": True,
                "qr_nonzero": any(abs(value) > 1e-12 for value in patch_powers.values()),
                "qr_patch_mean_w_m2": {
                    name: qr_values[name] for name in patch_powers
                },
            }
            manifest["patch_net_radiation_power_w"] = patch_powers
            if len(patch_powers) != len(patches):
                blockers.append("QR_PATCH_INCOMPLETE")
            elif not manifest["fields"]["qr_nonzero"]:
                blockers.append("QR_FIELD_ZERO")
            else:
                gross = math.fsum(abs(value) for value in patch_powers.values())
                signed = math.fsum(patch_powers.values())
                balance_error = abs(signed) / gross if gross else math.inf
                manifest["energy_balance"] = {
                    "patch_net_radiation_power_w": signed,
                    "gross_patch_radiation_power_w": gross,
                    "internal_radiation_balance_relative_error": balance_error,
                }
                if balance_error > float(reference["acceptance"][
                        "internal_radiation_balance_relative_error_max"
                ]):
                    blockers.append("PATCH_RADIATION_BALANCE_FAILED")
                hot = manifest["fields"]["qr_patch_mean_w_m2"].get("hot_plate")
                cold = manifest["fields"]["qr_patch_mean_w_m2"].get("cold_plate")
                expected_flux = float(reference["expected"]["net_flux_w_m2"])
                if hot is None or cold is None or expected_flux <= 0:
                    blockers.append("REFERENCE_FLUX_EVIDENCE_MISSING")
                else:
                    expected_signs = reference["expected"].get(
                        "qr_patch_sign_convention", {}
                    )
                    direction_ok = (
                        expected_signs.get("hot_plate") == "negative"
                        and expected_signs.get("cold_plate") == "positive"
                        and hot < 0.0 and cold > 0.0
                    )
                    relative_error = max(
                        abs(abs(hot) - expected_flux) / expected_flux,
                        abs(abs(cold) - expected_flux) / expected_flux,
                    )
                    manifest["reference_comparison"] = {
                        "expected_net_flux_w_m2": expected_flux,
                        "hot_plate_qr_w_m2": hot,
                        "cold_plate_qr_w_m2": cold,
                        "expected_qr_patch_sign_convention": expected_signs,
                        "direction_ok": direction_ok,
                        "relative_error": relative_error,
                        "limit": float(reference["acceptance"]["solver_flux_relative_error_max"]),
                    }
                    if not direction_ok:
                        blockers.append("REFERENCE_FLUX_DIRECTION_INVALID")
                    if relative_error > float(
                            reference["acceptance"]["solver_flux_relative_error_max"]
                    ):
                        blockers.append("REFERENCE_FLUX_OUT_OF_TOLERANCE")
        except (RadiationInputError, KeyError, TypeError, ValueError):
            blockers.append("QR_FIELD_INVALID")

    # Deduplicate while preserving a readable, deterministic order.
    manifest["blockers"] = list(dict.fromkeys(blockers))
    manifest["status"] = "PASS" if source_ok and not manifest["blockers"] else "NOT_EVALUATED"
    manifest["benchmark_ready"] = manifest["status"] == "PASS"
    _write_json(case / "radiation_manifest.json", manifest)
    return manifest
