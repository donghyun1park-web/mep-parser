def _strip_foam_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)
    return re.sub(r"//[^\n]*", "", text)


def _balanced_braces(text, opening_index):
    if opening_index >= len(text) or text[opening_index] != "{":
        raise RadiationInputError("OpenFOAM dictionary 중괄호를 찾지 못했습니다.")
    depth = 0
    for index in range(opening_index, len(text)):
        char = text[index]
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return text[opening_index + 1:index], index + 1
    raise RadiationInputError("OpenFOAM dictionary 중괄호가 닫히지 않았습니다.")


def _parse_foam_parenthesized_list(text, opening_index):
    """Parse the scalar-list subset emitted by createViewFactors F output."""
    if text[opening_index] != "(":
        raise RadiationInputError("view-factor 행렬 목록이 없습니다.")
    values = []
    index = opening_index + 1
    while True:
        while index < len(text) and text[index].isspace():
            index += 1
        if index >= len(text):
            raise RadiationInputError("view-factor 행렬 목록이 닫히지 않았습니다.")
        if text[index] == ")":
            return values, index + 1
        if text[index] == "(":
            nested, index = _parse_foam_parenthesized_list(text, index)
            values.append(nested)
            continue
        match = re.match(r"[^\s()]+", text[index:])
        if match is None:
            raise RadiationInputError("view-factor 행렬 토큰을 읽지 못했습니다.")
        token = match.group(0)
        index += len(token)
        while index < len(text) and text[index].isspace():
            index += 1
        # Some OpenFOAM list writers emit a count immediately before a nested
        # list (for example 6(...)). Validate and discard that count.
        if index < len(text) and text[index] == "(":
            try:
                declared = int(token)
            except ValueError as exc:
                raise RadiationInputError("view-factor 목록 길이가 올바르지 않습니다.") from exc
            nested, index = _parse_foam_parenthesized_list(text, index)
            if len(nested) != declared:
                raise RadiationInputError("view-factor 목록 길이와 선언값이 다릅니다.")
            values.append(nested)
            continue
        try:
            number = float(token)
        except ValueError as exc:
            raise RadiationInputError("view-factor 행렬에 숫자가 아닌 값이 있습니다.") from exc
        if not math.isfinite(number):
            raise RadiationInputError("view-factor 행렬에 유한하지 않은 값이 있습니다.")
        values.append(number)


def _parse_view_factor_matrix(path):
    try:
        text = _strip_foam_comments(Path(path).read_text(encoding="utf-8"))
    except OSError as exc:
        raise RadiationInputError(f"view-factor 행렬을 읽지 못했습니다: {exc}") from exc
    # Skip the FoamFile header, whose version number must never be mistaken for
    # the matrix size.
    header = re.search(r"\bFoamFile\s*\{", text)
    body_start = 0
    if header is not None:
        _, body_start = _balanced_braces(text, text.find("{", header.start()))
    match = re.search(r"\b(\d+)\s*\(", text[body_start:])
    if match is None:
        raise RadiationInputError("view-factor 행렬 차원을 찾지 못했습니다.")
    declared_rows = int(match.group(1))
    opening = body_start + match.end() - 1
    rows, _ = _parse_foam_parenthesized_list(text, opening)
    if len(rows) != declared_rows:
        raise RadiationInputError("view-factor 행렬 행 수와 선언값이 다릅니다.")
    matrix = []
    for row in rows:
        if not isinstance(row, list) or len(row) != declared_rows:
            raise RadiationInputError("view-factor 행렬이 정사각 행렬이 아닙니다.")
        if any(not isinstance(value, float) for value in row):
            raise RadiationInputError("view-factor 행렬 행에 숫자 이외의 값이 있습니다.")
        matrix.append(row)
    return matrix


def _parse_qr_patch_values(path):
    """Read means of the scalar value entries from a written qr field."""
    try:
        text = _strip_foam_comments(Path(path).read_text(encoding="utf-8"))
    except OSError as exc:
        raise RadiationInputError(f"qr field를 읽지 못했습니다: {exc}") from exc
    boundary = re.search(r"\bboundaryField\s*\{", text)
    if boundary is None:
        raise RadiationInputError("qr field에 boundaryField가 없습니다.")
    content, _ = _balanced_braces(text, text.find("{", boundary.start()))
    values = {}
    position = 0
    while True:
        patch = re.search(r"([A-Za-z_][A-Za-z0-9_]*)\s*\{", content[position:])
        if patch is None:
            break
        name = patch.group(1)
        opening = position + patch.end() - 1
        patch_content, position = _balanced_braces(content, opening)
        uniform = re.search(
            r"\bvalue\s+uniform\s+([+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?)\s*;",
            patch_content,
        )
        if uniform is not None:
            values[name] = float(uniform.group(1))
            continue
        nonuniform = re.search(
            r"\bvalue\s+nonuniform\s+(?:List<scalar>\s*)?(?:\d+\s*)?\((.*?)\)\s*;",
            patch_content,
            flags=re.DOTALL,
        )
        if nonuniform is None:
            continue
        numbers = [
            float(token) for token in re.findall(
                r"[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?",
                nonuniform.group(1),
            )
        ]
        if not numbers or not all(math.isfinite(value) for value in numbers):
            raise RadiationInputError(f"qr patch {name}의 값이 비어 있거나 유한하지 않습니다.")
        values[name] = math.fsum(numbers) / len(numbers)
    if not values:
        raise RadiationInputError("qr field의 patch 값을 읽지 못했습니다.")
    return values


def _latest_solver_qr(case):
    candidates = []
    for child in Path(case).iterdir():
        if not child.is_dir():
            continue
        try:
            value = float(child.name)
        except ValueError:
            continue
        if math.isfinite(value) and value > 0 and (child / "qr").is_file():
            candidates.append((value, child.name, child / "qr"))
    if not candidates:
        return None
    return max(candidates, key=lambda item: item[0])


def _source_integrity(case, benchmark_input):
    expected = benchmark_input.get("source_hashes")
    if not isinstance(expected, dict) or set(expected) != set(_TWO_PLATE_SOURCE_PATHS):
        return False, ["SOURCE_HASH_CONTRACT_INVALID"], {}
    current = {}
    blockers = []
    for relative in _TWO_PLATE_SOURCE_PATHS:
        path = Path(case) / relative
        if not path.is_file():
            blockers.append(f"SOURCE_INPUT_MISSING:{relative}")
            continue
        current[relative] = _sha256(path)
        if expected.get(relative) != current[relative]:
            blockers.append(f"SOURCE_HASH_MISMATCH:{relative}")
    return not blockers, blockers, current


